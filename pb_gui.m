    function loadScenario(~, ~)

        if S.busy
            return
        end

        [fileName, folderName] = uigetfile( ...
            '*.mat', ...
            'Charger un scenario Pollbuster');

        if isequal(fileName, 0)
            return
        end

        try
            loadedData = load( ...
                fullfile(folderName, fileName), ...
                'cfg', ...
                'schemaVersion');

            validSchema = ...
                isfield(loadedData, 'schemaVersion') ...
                && isnumeric(loadedData.schemaVersion) ...
                && isscalar(loadedData.schemaVersion) ...
                && loadedData.schemaVersion == 1;

            validConfiguration = ...
                isfield(loadedData, 'cfg') ...
                && isstruct(loadedData.cfg) ...
                && isscalar(loadedData.cfg);

            if ~validSchema || ~validConfiguration
                error( ...
                    'Pollbuster:InvalidScenario', ...
                    'Format de scenario non reconnu.');
            end

            if ~strcmp( ...
                    pb_get(loadedData.cfg, 'mode', '2027'), ...
                    '2027')

                error( ...
                    'Pollbuster:UnsupportedScenario', ...
                    'Cette interface est reservee aux scenarios 2027.');
            end

            applyConfiguration( ...
                loadedData.cfg, ...
                S.selected, ...
                true);

        catch loadError
            errordlg( ...
                loadError.message, ...
                'Chargement impossible');
        end

    end

