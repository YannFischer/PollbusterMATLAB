    function success = applyConfiguration( ...
            newConfiguration, ...
            newSelection, ...
            showDialog)

        success = false;

        if S.busy || ~isgraphics(H.fig)
            return
        end

        previousConfiguration = S.cfg;
        previousResult = S.result;
        previousSelection = S.selected;

        S.busy = true;

        busyCleanup = onCleanup(@finishBusy); %#ok<NASGU>

        set( ...
            H.fig, ...
            'Pointer', 'watch');

        setStatus('Calcul en cours...', false);

        drawnow;

        try
            % Ne pas écraser le dernier résultat avant un calcul réussi.

            newResult = pb_simulate( ...
                S.D, ...
                newConfiguration);

            validateResult(newResult);

            S.cfg = newConfiguration;
            S.result = newResult;
            S.selected = validSelection( ...
                newSelection, ...
                newResult);

            syncControls();
            syncTables();
            syncSelector();
            drawViews();
            updateSummary();

            setappdata( ...
                H.fig, ...
                'PollbusterConfig', ...
                S.cfg);

            setappdata( ...
                H.fig, ...
                'PollbusterResult', ...
                S.result);

            if isappdata(H.fig, 'PollbusterLastError')
                rmappdata( ...
                    H.fig, ...
                    'PollbusterLastError');
            end

            setStatus( ...
                ['Simulation conditionnelle aux hypotheses. ' ...
                 'Les pertes affichees ne sont pas ' ...
                 'l''abstention nationale.'], ...
                false);

            success = true;

        catch calculationError
            S.cfg = previousConfiguration;
            S.result = previousResult;
            S.selected = previousSelection;

            if isgraphics(H.fig)

                setappdata( ...
                    H.fig, ...
                    'PollbusterLastError', ...
                    calculationError);

                % Restaurer autant que possible l'affichage précédent.

                try
                    syncControls();
                    syncTables();

                    if hasResult()
                        syncSelector();
                        drawViews();
                        updateSummary();
                    end

                catch restorationError
                    fprintf( ...
                        2, ...
                        'Restauration de l''interface : %s\n', ...
                        restorationError.message);
                end

                if hasResult()
                    errorPrefix = ...
                        'Modification refusee, dernier resultat conserve : ';
                else
                    errorPrefix = ...
                        'Echec du calcul initial : ';
                end

                setStatus( ...
                    [errorPrefix, calculationError.message], ...
                    true);
            end

            fprintf( ...
                2, ...
                '%s\n', ...
                getReport( ...
                    calculationError, ...
                    'extended', ...
                    'hyperlinks', ...
                    'off'));

            if showDialog && isgraphics(H.fig)
                errordlg( ...
                    calculationError.message, ...
                    'Erreur de simulation');
            end
        end

    end

