    function syncTables()

        candidatesNow = pb_candidates( ...
            S.D, ...
            S.cfg);

        candidateData = cell( ...
            numel(candidatesNow), ...
            8);

        profileData = cell( ...
            numel(candidatesNow), ...
            numel(S.themeIds) + 1);

        for candidateIndex = 1:numel(candidatesNow)
            candidateNow = candidatesNow(candidateIndex);

            isMoved = ~isempty(candidateNow.pos);

            if isMoved
                politicalPosition = candidateNow.pos;
            else
                politicalPosition = candidateNow.by_hist;
            end

            candidateData(candidateIndex, :) = {
                any(strcmp(S.cfg.active, candidateNow.id)), ...
                candidateNow.name, ...
                candidateNow.noto, ...
                candidateNow.force, ...
                isMoved, ...
                politicalPosition(1), ...
                politicalPosition(2), ...
                candidateNow.zone
            };

            profileData{candidateIndex, 1} = ...
                candidateNow.name;

            candidateProfile = pb_get( ...
                S.cfg.themeProfiles, ...
                candidateNow.id, ...
                struct());

            for themeIndex = 1:numel(S.themeIds)
                profileData{candidateIndex, themeIndex + 1} = ...
                    pb_get( ...
                        candidateProfile, ...
                        S.themeIds{themeIndex}, ...
                        0);
            end
        end

        set( ...
            H.candidateTable, ...
            'Data', candidateData);

        set( ...
            H.profileTable, ...
            'Data', profileData);

        reservoirsNow = pb_build2027( ...
            S.D, ...
            S.cfg);

        reservoirData = cell( ...
            numel(reservoirsNow), ...
            5);

        for reservoirIndex = 1:numel(reservoirsNow)
            reservoirNow = reservoirsNow(reservoirIndex);

            floatingFields = fieldnames( ...
                reservoirNow.flot);

            floatingMass = 0;

            for floatingIndex = 1:numel(floatingFields)
                floatingMass = ...
                    floatingMass ...
                    + reservoirNow.flot ...
                    .(floatingFields{floatingIndex});
            end

            reservoirOverride = pb_get( ...
                S.cfg.reservoirOverrides, ...
                reservoirNow.id, ...
                struct());

            reservoirData(reservoirIndex, :) = {
                reservoirNow.id, ...
                reservoirNow.fid, ...
                floatingMass, ...
                reservoirNow.fidP, ...
                pb_get(reservoirOverride, 'scale', 1)
            };
        end

        set( ...
            H.reservoirTable, ...
            'Data', reservoirData);

    end

