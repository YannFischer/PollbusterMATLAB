                copiedAxes, ...
                'Units', 'normalized', ...
                'Position', exportPosition);

            set( ...
                temporaryFigure, ...
                'PaperPositionMode', 'auto', ...
                'InvertHardcopy', 'off');

            print( ...
                temporaryFigure, ...
                fullfile(folderName, fileName), ...
                '-dpng', ...
                '-r180');

            setStatus( ...
                'Graphique exporte en PNG.', ...
                false);

        catch exportError
            errordlg( ...
                exportError.message, ...
                'Export impossible');
        end

    end

