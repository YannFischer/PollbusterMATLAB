    function value = parameterValue(key, configuration)

        if any(strcmp(key, {'ALPHA', 'GAMMA'}))
            kernelOptions = pb_get( ...
                configuration.options, ...
                'pb', ...
                struct());

            value = pb_get( ...
                kernelOptions, ...
                key, ...
                S.D.core.params.(key));

        else
            fallbackOptions = struct( ...
                'homeSigma', 0.35, ...
                'homeZoneSigma', 0.15, ...
                'freeSigma', 0.25);

            fallbackValue = pb_get( ...
                fallbackOptions, ...
                key, ...
                0);

            value = pb_get( ...
                configuration.options, ...
                key, ...
                fallbackValue);
        end

    end

    function configuration = setParameter( ...
            configuration, key, value)

        if any(strcmp(key, {'ALPHA', 'GAMMA'}))

            if ~isfield(configuration.options, 'pb')
                configuration.options.pb = struct();
            end

            configuration.options.pb.(key) = value;

        else
            configuration.options.(key) = value;
        end

    end

    %% Calcul transactionnel

    function refresh(varargin)

