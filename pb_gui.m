    function editCandidate(~, event)

        if S.busy || isempty(event.Indices)
            return
        end

        row = event.Indices(1);
        column = event.Indices(2);

        tableData = get( ...
            H.candidateTable, ...
            'Data');

        newConfiguration = S.cfg;
        candidateId = S.allIds{row};

        try
            switch column

                case 1
                    activeMask = cell2mat( ...
                        tableData(:, 1));

                    if ~any(activeMask)
                        error( ...
                            'Pollbuster:NoCandidate', ...
                            'Gardez au moins un candidat actif.');
                    end

                    newConfiguration.active = ...
                        S.allIds(logical(activeMask(:)'));

                case {3, 4, 5, 6, 7, 8}
                    override = pb_get( ...
                        newConfiguration.candidateOverrides, ...
                        candidateId, ...
                        struct());

                    switch column

                        case 3
                            validateattributes( ...
                                tableData{row, 3}, ...
                                {'numeric'}, ...
                                {
                                    'scalar'
                                    'finite'
                                    '>='
                                    0
                                    '<='
                                    1
                                });

                            override.noto = ...
                                tableData{row, 3};

                        case 4
                            validateattributes( ...
                                tableData{row, 4}, ...
                                {'numeric'}, ...
                                {
                                    'scalar'
                                    'finite'
                                    '>='
                                    0
                                    '<='
                                    10
                                });

                            override.force = ...
                                tableData{row, 4};

                        case 5
                            if tableData{row, 5}
                                validatePoliticalPosition( ...
                                    tableData{row, 6}, ...
                                    tableData{row, 7});

                                override.pos = [
                                    tableData{row, 6}
                                    tableData{row, 7}
                                ]';

                            else
                                override.pos = [];
                            end

                        case {6, 7}
                            if ~tableData{row, 5}
                                syncTables();

                                setStatus( ...
                                    ['Cocher Deplacer avant de ' ...
                                     'modifier les coordonnees.'], ...
                                    false);

                                return
                            end

                            validatePoliticalPosition( ...
                                tableData{row, 6}, ...
                                tableData{row, 7});

                            override.pos = [
                                tableData{row, 6}
                                tableData{row, 7}
                            ]';

                        case 8
                            override.zone = ...
                                tableData{row, 8};
                    end

                    newConfiguration.candidateOverrides ...
                        .(candidateId) = override;

                otherwise
                    return
            end

            applyConfiguration( ...
                newConfiguration, ...
                candidateId, ...
                true);

        catch editError
            syncTables();

            errordlg( ...
                editError.message, ...
                'Parametre invalide');
        end

    end

