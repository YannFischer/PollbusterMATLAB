        try
            temporaryFigure = figure( ...
                'Visible', 'off', ...
                'Color', S.background, ...
                'Position', [100, 100, 1600, 950]);

            temporaryCleanup = onCleanup( ...
                @() guiDeleteFigure(temporaryFigure)); %#ok<NASGU>

            copiedAxes = copyobj( ...
                sourceAxes, ...
                temporaryFigure);

            if isequal(selectedTab, H.sourceTab)
                exportPosition = [0.32, 0.15, 0.63, 0.73];

            elseif isequal(selectedTab, H.socioTab)
                exportPosition = [0.25, 0.15, 0.70, 0.73];

