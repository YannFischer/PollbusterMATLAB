    function validateResult(candidateResult)

        requiredFields = {
            'ids'
            'candidates'
            'reservoirs'
            'V'
            'T'
            'E'
            'pct'
            'sources'
            'coordinates'
            'barycentre'
            'lost'
            'totalReservoir'
            'conservationError'
        };

        if ~isstruct(candidateResult) ...
                || ~isscalar(candidateResult)

            error( ...
                'Pollbuster:InvalidResult', ...
                'Le moteur doit renvoyer une structure scalaire.');
        end

        for fieldIndex = 1:numel(requiredFields)

            if ~isfield( ...
                    candidateResult, ...
                    requiredFields{fieldIndex})

                error( ...
                    'Pollbuster:MissingResultField', ...
                    'Champ absent du resultat : "%s".', ...
                    requiredFields{fieldIndex});
            end
        end

        candidateCount = numel(candidateResult.ids);

        if candidateCount == 0
            error( ...
                'Pollbuster:EmptyResult', ...
                'Le resultat ne contient aucun candidat.');
        end

        if numel(candidateResult.pct) ~= candidateCount ...
                || numel(candidateResult.T) ~= candidateCount ...
                || size(candidateResult.V, 1) ~= candidateCount ...
                || size(candidateResult.sources, 2) ~= candidateCount

            error( ...
                'Pollbuster:InvalidResultDimensions', ...
                'Dimensions incoherentes dans le resultat du moteur.');
        end

        if any(~isfinite(candidateResult.pct(:))) ...
                || any(~isfinite(candidateResult.V(:))) ...
                || ~isfinite(candidateResult.E) ...
                || candidateResult.E <= 0

            error( ...
                'Pollbuster:InvalidNumericalResult', ...
                'Le moteur a produit un resultat numerique invalide.');
        end

    end

    function available = hasResult()

        available = ...
            isstruct(S.result) ...
            && isscalar(S.result) ...
            && isfield(S.result, 'ids') ...
            && ~isempty(S.result.ids);

    end

    function selection = validSelection( ...
            requestedSelection, candidateResult)

        if any(strcmp( ...
                candidateResult.ids, ...
                requestedSelection))

            selection = requestedSelection;

        else
            selection = candidateResult.ids{1};
        end

    end

