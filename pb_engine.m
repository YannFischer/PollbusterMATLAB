function out = pb_engine(D, reservoirs, candidates, opt)
    %PB_ENGINE Répartition des réservoirs électoraux du moteur V18.
    %
    % Unités :
    %   - réservoirs : millions de voix ;
    %   - V et T     : nombres de voix ;
    %   - pct        : pourcentages des suffrages exprimés simulés.
    %
    % Les noms des variables internes des fonctions imbriquées sont
    % volontairement distincts de ceux du moteur principal.

    if nargin < 4 || isempty(opt)
        opt = struct();
    end

    % Initialisation

    engineReservoirs = pb_cells(reservoirs);
    engineCandidates = pb_cells(candidates);

    engineCandidateCount = numel(engineCandidates);
    engineReservoirCount = numel(engineReservoirs);

    engineCategories = D.core.pcs;
    engineCategoryCount = numel(engineCategories);

    if engineCandidateCount == 0
        error( ...
            'Pollbuster:NoCandidate', ...
        'Activez au moins un candidat.');
    end

    engineIds = cell(1, engineCandidateCount);
    engineFamilies = cell(1, engineCandidateCount);

    engineVotes = zeros( ...
        engineCandidateCount, ...
        engineCategoryCount);

    engineLost = zeros(1, engineCategoryCount);

    engineSources = zeros( ...
        engineReservoirCount, ...
        engineCandidateCount);

    engineParticipationConfig = pb_get( ...
        opt, ...
        'part', ...
        D.core.part);

    enginePopulation = [engineCategories.n];

    engineParticipation = zeros( ...
        1, ...
        engineCategoryCount);

    for engineG = 1:engineCategoryCount
        engineCategoryId = engineCategories(engineG).id;

        engineParticipation(engineG) = ...
            engineParticipationConfig.(engineCategoryId);
    end

    % Candidats et familles représentées par leur ancien candidat

    engineIncumbents = struct();

    for engineC = 1:engineCandidateCount
        engineCandidate = engineCandidates{engineC};

        engineIds{engineC} = engineCandidate.id;
        engineFamilies{engineC} = engineCandidate.fam;

        if pb_get(engineCandidate, 'meme', false)
            engineRepresentedFamilies = [ ...
                                             {engineCandidate.fam}, ...
                                             pb_cells(pb_get( ...
                                             engineCandidate, ...
                                             'fams', ...
                                             {})) ...
                                         ];

            for engineF = 1:numel(engineRepresentedFamilies)
                engineFamilyId = ...
                    engineRepresentedFamilies{engineF};

                engineIncumbents.(engineFamilyId) = true;
            end

        end

    end

    % Ancrage des profils sur les trajectoires historiques

    engineProfiles = pb_get( ...
        opt, ...
        'prof', ...
        struct());

    enginePresidentialProfiles = struct();

    engineTrajectory = pb_get( ...
        opt, ...
        'traj', ...
        struct());

    if isfield(engineTrajectory, 'profils')
        engineProfileKeys = fieldnames( ...
            engineTrajectory.profils);

        for engineF = 1:numel(engineProfileKeys)
            engineProfileKey = engineProfileKeys{engineF};

            engineHistoryPoints = pb_cells( ...
                engineTrajectory.profils.(engineProfileKey));

            if isempty(engineHistoryPoints)
                continue
            end

            enginePresidentialProfile = ...
                engineHistoryPoints{end}.pen;

            engineDelta = pb_get( ...
                engineTrajectory, ...
                'delta', ...
                0);

            if engineDelta ~= 0 && numel(engineHistoryPoints) > 1
                enginePreviousProfile = ...
                    engineHistoryPoints{end - 1}.pen;

                engineProfileFields = fieldnames( ...
                    enginePresidentialProfile);

                for engineJ = 1:numel(engineProfileFields)
                    engineProfileField = ...
                        engineProfileFields{engineJ};

                    enginePreviousValue = pb_get( ...
                        enginePreviousProfile, ...
                        engineProfileField, ...
                        0);

                    engineCurrentValue = ...
                        enginePresidentialProfile.(engineProfileField);

                    if enginePreviousValue > 0 && engineCurrentValue > 0
                        enginePresidentialProfile.(engineProfileField) = ...
                            engineCurrentValue ...
                            * (engineCurrentValue / enginePreviousValue) ...
                            ^ engineDelta;
                    end

                end

            end

            enginePresidentialProfiles.(engineProfileKey) = ...
                enginePresidentialProfile;

            engineTrajectoryForce = pb_get( ...
                engineTrajectory, ...
                'force', ...
                0);

            if pb_get(engineIncumbents, engineProfileKey, false)

                if isfield(engineTrajectory, 'forceMeme')
                    engineTrajectoryForce = ...
                        engineTrajectory.forceMeme;
                end

            end

            if isfield(engineProfiles, engineProfileKey) ...
                    && engineTrajectoryForce > 0

                engineProfileFields = fieldnames( ...
                    engineProfiles.(engineProfileKey));

                for engineJ = 1:numel(engineProfileFields)
                    engineProfileField = ...
                        engineProfileFields{engineJ};

                    if isfield( ...
                            enginePresidentialProfile, ...
                            engineProfileField)

                        engineBaseValue = ...
                            engineProfiles.(engineProfileKey) ...
                            .(engineProfileField);

                        engineHistoricalValue = ...
                            enginePresidentialProfile ...
                            .(engineProfileField);

                        engineProfiles.(engineProfileKey) ...
                            .(engineProfileField) = ...
                            max(engineBaseValue, 1e-6) ...
                            ^ (1 - engineTrajectoryForce) ...
                            * max(engineHistoricalValue, 1e-6) ...
                            ^ engineTrajectoryForce;
                    end

                end

            end

        end

    end

    % Construction des candidats transmis au noyau d'attraction

    engineModelTemplate = struct( ...
        'id', '', ...
        'zone', '', ...
        'by_hist', [], ...
        'pos', [], ...
        'noto', 0, ...
        'ancrage', 0, ...
        'move', 1);

    engineModel = repmat( ...
        engineModelTemplate, ...
        engineCandidateCount + 1, ...
        1);

    for engineC = 1:engineCandidateCount
        engineCandidate = engineCandidates{engineC};

        engineFamilyIndex = find( ...
            cellfun( ...
            @(candidateReservoir) strcmp( ...
            candidateReservoir.id, ...
            engineCandidate.fam), ...
            engineReservoirs), ...
            1);

        if isempty(engineFamilyIndex)
            error( ...
                'Pollbuster:MissingFamily', ...
                'Reservoir absent pour la famille "%s".', ...
                engineCandidate.fam);
        end

        engineFamilyReservoir = ...
            engineReservoirs{engineFamilyIndex};

        engineFloating = pb_get( ...
            engineFamilyReservoir, ...
            'flot', ...
            struct());

        engineFloatingFields = fieldnames(engineFloating);
        engineFloatingMass = 0;

        for engineJ = 1:numel(engineFloatingFields)
            engineFloatingField = ...
                engineFloatingFields{engineJ};

            engineFloatingMass = engineFloatingMass ...
                + engineFloating.(engineFloatingField);
        end

        engineModel(engineC).id = engineCandidate.id;
        engineModel(engineC).zone = engineCandidate.zone;

        engineModel(engineC).by_hist = pb_get( ...
            engineCandidate, ...
            'by_hist', ...
            []);

        engineModel(engineC).pos = pb_get( ...
            engineCandidate, ...
            'pos', ...
            []);

        engineLed = pb_get( ...
            engineCandidate, ...
            'led', ...
            engineFamilyReservoir.fid);

        engineDefaultNotoriety = max( ...
            0.2, ...
            1 - exp(-engineLed / D.notoriety.NP.LED_SCALE));

        engineModel(engineC).noto = pb_get( ...
            engineCandidate, ...
            'noto', ...
            engineDefaultNotoriety);

        if engineFamilyReservoir.fid > 0
            engineModel(engineC).ancrage = ...
                engineFamilyReservoir.fid ...
                / (engineFamilyReservoir.fid + engineFloatingMass);
        else
            engineModel(engineC).ancrage = pb_get( ...
                opt, ...
                'ancrageVacant', ...
                0.5);
        end

        engineHomeSigma = pb_get( ...
            opt, ...
            'homeSigma', ...
            0.35);

        if engineHomeSigma ~= 0 ...
                && ~isempty(engineModel(engineC).pos) ...
                && ~isempty(engineModel(engineC).by_hist)

            engineCanonicalZone = ...
                getZone(engineCandidate.zone);

            engineDistanceHistorical = norm( ...
                engineModel(engineC).pos(:) ...
                - engineModel(engineC).by_hist(:));

            engineDistanceCanonical = norm( ...
                engineModel(engineC).pos(:) ...
                - engineCanonicalZone.mu(:));

            engineMovementDistance = min( ...
                engineDistanceHistorical, ...
                engineDistanceCanonical);

            engineModel(engineC).move = exp( ...
                -engineMovementDistance ^ 2 ...
                / (2 * engineHomeSigma ^ 2));
        end

    end

    % Option d'abstention ajoutée au noyau.

    engineModel(end).id = 'abst';
    engineModel(end).zone = 'Z0';
    engineModel(end).by_hist = [0.07, -1.32];
    engineModel(end).noto = 1;
    engineModel(end).ancrage = 0;

    [engineProbabilities, engineKernel] = pb_core( ...
        D, ...
        engineModel, ...
        pb_get(opt, 'pb', struct()));

    % Usure appliquée aux probabilités

    engineKappa = pb_get(opt, 'kappa', 0);
    engineContinuity = pb_get(opt, 'cont', struct());

    if engineKappa ~= 0

        for engineC = 1:engineCandidateCount
            engineWear = pb_get( ...
                engineContinuity, ...
                engineIds{engineC}, ...
                0);

            engineProbabilities(engineC, :) = ...
                engineProbabilities(engineC, :) ...
                * (1 - engineKappa * engineWear);
        end

    end

    % Coefficients thématiques

    engineThemeBoost = struct();
    engineThemes = pb_get(opt, 'themes', struct());

    if isfield(engineThemes, 'S') ...
            && isfield(engineThemes, 'PI') ...
            && isfield(engineThemes, 'O')

        engineThemeKeys = fieldnames(engineThemes.S);
        engineThemeZones = fieldnames(engineThemes.PI);

        engineTheta = pb_get( ...
            engineThemes, ...
            'theta', ...
            1);

        for engineZ = 1:numel(engineThemeZones)
            engineThemeZoneId = ...
                engineThemeZones{engineZ};

            engineThemeWeights = zeros( ...
                1, ...
                numel(engineThemeKeys));

            for engineJ = 1:numel(engineThemeKeys)
                engineThemeKey = engineThemeKeys{engineJ};

                engineThemeWeights(engineJ) = ...
                    engineThemes.S.(engineThemeKey) ...
                    * pb_get( ...
                    engineThemes.PI.(engineThemeZoneId), ...
                    engineThemeKey, ...
                    0);
            end

            engineThemeWeightTotal = ...
                sum(engineThemeWeights);

            if engineThemeWeightTotal <= 0
                continue
            end

            engineThemeWeights = ...
                engineThemeWeights / engineThemeWeightTotal;

            engineThemeStrength = zeros( ...
                1, ...
                engineCandidateCount);

            for engineC = 1:engineCandidateCount
                engineCandidateThemeProfile = pb_get( ...
                    engineThemes.O, ...
                    engineIds{engineC}, ...
                    struct());

                for engineJ = 1:numel(engineThemeKeys)
                    engineThemeKey = engineThemeKeys{engineJ};

                    engineThemeStrength(engineC) = ...
                        engineThemeStrength(engineC) ...
                        + engineThemeWeights(engineJ) ...
                        * pb_get( ...
                        engineCandidateThemeProfile, ...
                        engineThemeKey, ...
                        0);
                end

            end

            engineThemeAverage = mean( ...
                engineThemeStrength);

            if engineThemeAverage > 0
                engineThemeStrength = ...
                    (engineThemeStrength / engineThemeAverage) ...
                    .^ engineTheta;
            else
                engineThemeStrength = ones( ...
                    1, ...
                    engineCandidateCount);
            end

            engineThemeBoost.(engineThemeZoneId) = ...
                engineThemeStrength;
        end

    end

    % Répartition des réservoirs

    engineBeta = pb_get(opt, 'beta', 1);

    engineBetaVacant = pb_get( ...
        opt, ...
        'betaVac', ...
        engineBeta);

    engineFloatingAbsorption = pb_get( ...
        opt, ...
        'absFlot', ...
        0.3);

    for engineR = 1:engineReservoirCount
        engineReservoir = engineReservoirs{engineR};
        engineVotesBefore = sum(engineVotes, 2);

        engineReservoir.flot = pb_get( ...
            engineReservoir, ...
            'flot', ...
            struct());

        engineReservoir.orig = pb_get( ...
            engineReservoir, ...
            'orig', ...
            struct());

        % Partie fidèle du réservoir

        if engineReservoir.fid ~= 0
            engineHeirs = find( ...
                cellfun( ...
                @(heirCandidate) belongsToFamily( ...
                heirCandidate, ...
                engineReservoir.id), ...
                engineCandidates));

            engineFamilyVacant = isempty(engineHeirs);
            engineRetainedMovementShare = 1;

            if ~engineFamilyVacant
                engineRetainedMovementShare = max( ...
                    [engineModel(engineHeirs).move]);
            end

            engineOriginFields = fieldnames( ...
                engineReservoir.orig);

            engineOriginMass = 0;

            for engineJ = 1:numel(engineOriginFields)
                engineOriginId = engineOriginFields{engineJ};

                engineOriginMass = engineOriginMass ...
                    + engineReservoir.orig.(engineOriginId);
            end

            enginePresidentialMass = min( ...
                engineReservoir.fid, ...
                pb_get(engineReservoir, 'fidP', 0));

            engineBaseMass = max( ...
                0, ...
                engineReservoir.fid ...
                - enginePresidentialMass ...
                - engineOriginMass);

            engineSegmentMasses = [ ...
                                       engineBaseMass, ...
                                       enginePresidentialMass];

            engineSegmentOrigins = { ...
                                        engineReservoir.id, ...
                                        engineReservoir.id};

            engineBasicProfile = pb_get( ...
                engineProfiles, ...
                engineReservoir.id, ...
                struct());

            enginePresidentialProfile = pb_get( ...
                enginePresidentialProfiles, ...
                engineReservoir.id, ...
                engineBasicProfile);

            engineSegmentProfiles = { ...
                                         engineBasicProfile, ...
                                         enginePresidentialProfile};

            for engineJ = 1:numel(engineOriginFields)
                engineOriginId = engineOriginFields{engineJ};

                engineSegmentMasses(end + 1) = ...
                    engineReservoir.orig.(engineOriginId);

                engineSegmentOrigins{end + 1} = ...
                    engineOriginId;

                engineSegmentProfiles{end + 1} = ...
                    engineBasicProfile;
            end

            if engineFamilyVacant
                engineSegmentBeta = engineBetaVacant;
            else
                engineSegmentBeta = engineBeta;
            end

            for engineJ = 1:numel(engineSegmentMasses)

                if engineSegmentMasses(engineJ) <= 0
                    continue
                end

                engineCategoryCounts = splitReservoir( ...
                    engineSegmentMasses(engineJ), ...
                    engineReservoir, ...
                    engineSegmentProfiles{engineJ});

                for engineG = 1:engineCategoryCount
                    engineHomeMass = ...
                        engineCategoryCounts(engineG) ...
                        * engineRetainedMovementShare;

                    engineLost(engineG) = ...
                        engineLost(engineG) ...
                        + allocate( ...
                        engineG, ...
                        engineHomeMass, ...
                        engineReservoir.zone, ...
                        engineReservoir.id, ...
                        '', ...
                        engineSegmentBeta, ...
                        pb_get(opt, 'absFid', 0), ...
                        engineSegmentOrigins{engineJ});

                    if engineRetainedMovementShare < 1
                        engineFreeMass = ...
                            engineCategoryCounts(engineG) ...
                            * (1 - engineRetainedMovementShare);

                        engineLost(engineG) = ...
                            engineLost(engineG) ...
                            + allocateFree( ...
                            engineG, ...
                            engineFreeMass, ...
                            engineReservoir.zone, ...
                            engineFloatingAbsorption);
                    end

                end

            end

        end

        % Partie flottante du réservoir

        engineFloatingZones = fieldnames( ...
            engineReservoir.flot);

        for engineJ = 1:numel(engineFloatingZones)
            engineFloatZoneId = ...
                engineFloatingZones{engineJ};

            engineFloatingProfile = pb_get( ...
                engineProfiles, ...
                engineReservoir.id, ...
                struct());

            engineCategoryCounts = splitReservoir( ...
                engineReservoir.flot.(engineFloatZoneId), ...
                engineReservoir, ...
                engineFloatingProfile);

            if pb_get(opt, 'lastVote', true)
                engineLastZoneId = engineFloatZoneId;
            else
                engineLastZoneId = '';
            end

            engineFloatingBeta = pb_get( ...
                opt, ...
                'betaFlot', ...
                engineBetaVacant);

            for engineG = 1:engineCategoryCount
                engineLost(engineG) = ...
                    engineLost(engineG) ...
                    + allocate( ...
                    engineG, ...
                    engineCategoryCounts(engineG), ...
                    engineFloatZoneId, ...
                    '', ...
                    engineLastZoneId, ...
                    engineFloatingBeta, ...
                    engineFloatingAbsorption, ...
                    engineReservoir.id);
            end

        end

        engineSources(engineR, :) = ...
            (sum(engineVotes, 2) - engineVotesBefore)';
    end

    % Totaux et scores

    engineTotals = sum(engineVotes, 2);
    engineExpressed = sum(engineTotals);

    if ~isfinite(engineExpressed) || engineExpressed <= 0
        error( ...
            'Pollbuster:NoVotes', ...
        'Aucun suffrage valide attribue aux candidats.');
    end

    enginePercentages = ...
        100 * engineTotals / engineExpressed;

    % Les lignes doivent respecter exactement l'ordre des colonnes
    % de engineVotes, donc l'ordre de engineCategories.

    engineSocialPositions = zeros( ...
        engineCategoryCount, ...
        2);

    for engineJ = 1:engineCategoryCount
        engineSocialCategoryId = ...
            engineCategories(engineJ).id;

        if strcmp(engineSocialCategoryId, 'inact')

            % Coordonnées brutes du référentiel PCS_LIVRE.
            % Ne pas utiliser ici les coordonnées transformées PCSPOS.

            engineSocialPoint = [ ...
                -2.5687835393427796, ...
                -3.3472027936890765];

        elseif isfield( ...
                D.history.POSTES, ...
                engineSocialCategoryId)

            engineSocialPoint = ...
                D.history.POSTES.(engineSocialCategoryId);

        else
            error( ...
                'Pollbuster:MissingSocialPosition', ...
                'Coordonnees sociales absentes pour la categorie "%s".', ...
                engineSocialCategoryId);
        end

        engineSocialPositions(engineJ, :) = ...
            engineSocialPoint(:)';
    end

    %% Position de chaque candidat sur toutes les catégories

    engineSocialTotals = sum( ...
        engineVotes, ...
        2);

    engineCoordinates = nan( ...
        engineCandidateCount, ...
        2);

    engineValidCoordinates = ...
        engineSocialTotals > 0;

    engineCoordinates(engineValidCoordinates, :) = ...
        (engineVotes(engineValidCoordinates, :) ...
        * engineSocialPositions) ...
        ./ engineSocialTotals(engineValidCoordinates);

    %% Barycentre général sur toutes les catégories

    engineMapCategoryTotals = sum( ...
        engineVotes, ...
        1);

    engineSocialMass = sum( ...
        engineMapCategoryTotals);

    if engineSocialMass > 0
        engineBarycentre = ...
            engineMapCategoryTotals ...
            * engineSocialPositions ...
            / engineSocialMass;
    else
        engineBarycentre = [NaN, NaN];
    end

    % Conservation des masses des réservoirs

    engineOriginalMass = 0;

    for engineR = 1:engineReservoirCount
        engineReservoir = engineReservoirs{engineR};

        engineOriginalMass = ...
            engineOriginalMass + engineReservoir.fid;

        engineFloating = pb_get( ...
            engineReservoir, ...
            'flot', ...
            struct());

        engineFloatingFields = fieldnames( ...
            engineFloating);

        for engineJ = 1:numel(engineFloatingFields)
            engineFloatingField = ...
                engineFloatingFields{engineJ};

            engineOriginalMass = ...
                engineOriginalMass ...
                + engineFloating.(engineFloatingField);
        end

    end

    engineOriginalVotes = ...
        engineOriginalMass * 1e6;

    engineConservationError = ...
        engineExpressed ...
        + sum(engineLost) ...
        - engineOriginalVotes;

    % Sortie

    out = struct();

    out.ids = engineIds;
    out.candidates = engineCandidates;
    out.reservoirs = engineReservoirs;

    out.V = engineVotes;
    out.T = engineTotals;
    out.E = engineExpressed;
    out.pct = enginePercentages;

    out.lost = engineLost;
    out.P = engineProbabilities;

    out.coordinates = engineCoordinates;
    out.barycentre = engineBarycentre;

    out.sources = engineSources;
    out.boost = engineThemeBoost;
    out.kernel = engineKernel;

    out.totalReservoir = engineOriginalVotes;
    out.conservationError = engineConservationError;

    % Fonctions imbriquées

    function zoneData = getZone(zoneId)

        if isstring(zoneId) && isscalar(zoneId)
            zoneId = char(zoneId);
        end

        if ~ischar(zoneId) ...
                || ~isrow(zoneId) ...
                || isempty(zoneId)

            error( ...
                'Pollbuster:InvalidZoneType', ...
                ['Une zone doit etre un texte comme ''Z4'', ' ...
             'pas une valeur de type "%s".'], ...
                class(zoneId));
        end

        zoneMatchIndex = find( ...
            strcmp({D.core.zones.id}, zoneId), ...
            1);

        if isempty(zoneMatchIndex)
            error( ...
                'Pollbuster:UnknownZone', ...
                'Zone inconnue : "%s".', ...
                zoneId);
        end

        zoneData = D.core.zones(zoneMatchIndex);
    end

    function familyMatch = belongsToFamily( ...
            familyCandidate, ...
            familyId)

        familyAdditional = pb_cells( ...
            pb_get(familyCandidate, 'fams', {}));

        familyMatch = ...
            strcmp(familyCandidate.fam, familyId) ...
            || any(strcmp(familyAdditional, familyId));
    end

    function splitCounts = splitReservoir( ...
            splitMass, ...
            splitReservoirData, ...
            splitProfile)

        splitWeights = zeros( ...
            1, ...
            engineCategoryCount);

        splitSourceZone = getZone( ...
            splitReservoirData.zone);

        for splitIndex = 1:engineCategoryCount
            splitCategory = ...
                engineCategories(splitIndex).id;

            splitPenetration = pb_get( ...
                splitProfile, ...
                splitCategory, ...
                0);

            if splitPenetration == 0
                splitPenetration = mean( ...
                    D.core.hist.(splitSourceZone.key) ...
                    .(splitCategory));
            end

            splitWeights(splitIndex) = ...
                splitPenetration ...
                * enginePopulation(splitIndex) ...
                * engineParticipation(splitIndex);
        end

        splitTotal = sum(splitWeights);

        if ~isfinite(splitTotal) || splitTotal <= 0
            error( ...
                'Pollbuster:InvalidProfile', ...
                ['Profil ou participation invalide ' ...
             'pour le reservoir "%s".'], ...
                splitReservoirData.id);
        end

        splitCounts = ...
            splitMass * 1e6 * splitWeights / splitTotal;
    end

    function homeValue = homeZone( ...
            homeCandidateIndex, ...
            homeZoneId)

        if strcmp( ...
                engineModel(homeCandidateIndex).zone, ...
                homeZoneId)

            homeValue = 1;
            return
        end

        homeZoneSigma = pb_get( ...
            opt, ...
            'homeZoneSigma', ...
            0.15);

        if homeZoneSigma == 0
            homeValue = 0;
            return
        end

        homePosition = pb_get( ...
            engineModel(homeCandidateIndex), ...
            'pos', ...
            pb_get( ...
            engineModel(homeCandidateIndex), ...
            'by_hist', ...
            []));

        if isempty(homePosition)
            homeValue = 0;
            return
        end

        homeZoneData = getZone(homeZoneId);

        homeDistanceSquared = sum( ...
            (homePosition(:) - homeZoneData.mu(:)) .^ 2);

        homeValue = exp( ...
            -homeDistanceSquared ...
            / (2 * homeZoneSigma ^ 2));
    end

    function allocAbstention = allocate( ...
            allocCategoryIndex, ...
            allocMass, ...
            allocZoneId, ...
            allocHomeFamily, ...
            allocLastZone, ...
            allocBeta, ...
            allocAbsorption, ...
            allocOriginFamily)

        if allocMass == 0
            allocAbstention = 0;
            return
        end

        allocPermeability = pb_get( ...
            D.core.porosity, ...
            allocZoneId, ...
            struct());

        allocFamilyPorosities = pb_get( ...
            opt, ...
            'poroFam', ...
            struct());

        if ~isempty(allocHomeFamily)
            allocPermeability = pb_get( ...
                allocFamilyPorosities, ...
                allocHomeFamily, ...
                allocPermeability);
        end

        allocHomeGain = pb_get(opt, 'home', 4);

        if isempty(allocHomeFamily)
            allocHomeGain = pb_get( ...
                opt, ...
                'homeFlot', ...
                allocHomeGain);
        end

        allocThematic = pb_get( ...
            engineThemeBoost, ...
            allocZoneId, ...
            ones(1, engineCandidateCount));

        allocPowerOut = pb_get( ...
            opt, ...
            'betaOut', ...
            allocBeta);

        allocPowerHome = pb_get( ...
            opt, ...
            'betaHome', ...
            allocBeta);

        allocLambda = pb_get(opt, 'lambda', 1);
        allocOriginBonus = pb_get(opt, 'homeOrig', 0);

        allocGrouping = pb_get( ...
            opt, ...
            'groupes', ...
        'fam');

        allocForceConfig = pb_get( ...
            opt, ...
            'force', ...
            struct());

        allocGroupKeys = cell( ...
            1, ...
            engineCandidateCount);

        allocWeights = zeros( ...
            1, ...
            engineCandidateCount);

        for allocC = 1:engineCandidateCount
            allocCandidate = ...
                engineCandidates{allocC};

            % Groupe du candidat

            if strcmp(allocGrouping, 'aucun')
                allocGroupKeys{allocC} = ...
                    engineIds{allocC};

            elseif strcmp(allocGrouping, 'heritiers') ...
                    && ~isempty(allocHomeFamily) ...
                    && belongsToFamily( ...
                    allocCandidate, ...
                    allocHomeFamily)

                allocGroupKeys{allocC} = ...
                    ['~', allocHomeFamily];

            else
                allocGroupKeys{allocC} = ...
                    engineFamilies{allocC};
            end

            % Bonus lié à l'origine présidentielle

            allocInherited = 0;

            if allocOriginBonus ~= 0 ...
                    && ~isempty(allocOriginFamily) ...
                    && belongsToFamily( ...
                    allocCandidate, ...
                    allocOriginFamily)

                allocAllowOtherOrigin = ...
                    ~pb_get(opt, 'homeOrigMeme', true);

                allocSameOriginCandidate = pb_get( ...
                    engineIncumbents, ...
                    allocOriginFamily, ...
                    false);

                if allocAllowOtherOrigin ...
                        || allocSameOriginCandidate

                    allocInherited = allocOriginBonus;
                else
                    allocInherited = ...
                        allocOriginBonus ...
                        * pb_get(opt, 'homeOrigAutre', 0);
                end

            end

            % Proximité avec la famille ou la dernière zone

            allocAffinity = 0;

            if ~isempty(allocHomeFamily)

                if ~strcmp( ...
                        allocOriginFamily, ...
                        allocHomeFamily) ...
                        && ~belongsToFamily( ...
                        allocCandidate, ...
                        allocHomeFamily)

                    allocAffinity = allocInherited;
                end

            elseif ~isempty(allocLastZone)
                allocAffinity = max( ...
                    homeZone(allocC, allocLastZone), ...
                    allocInherited);
            end

            allocOwned = ...
                ~isempty(allocHomeFamily) ...
                && belongsToFamily( ...
                allocCandidate, ...
                allocHomeFamily);

            allocIsHome = allocOwned || allocAffinity > 0;
            allocHomeShare = allocAffinity;

            if allocOwned
                allocHomeShare = 1;
            end

            % Attraction extérieure

            allocMultiplier = ...
                allocThematic(allocC) ...
                * pb_get( ...
                allocForceConfig, ...
                engineIds{allocC}, ...
                1);

            allocCandidatePorosity = pb_get( ...
                allocPermeability, ...
                allocCandidate.zone, ...
                0);

            allocOtherWeight = ...
                engineProbabilities( ...
                allocC, ...
                allocCategoryIndex) ...
                ^ allocPowerOut ...
                * allocCandidatePorosity ...
                ^ allocLambda;

            % Attraction familiale

            if allocIsHome
                allocRecognition = 1;

                if pb_get(opt, 'homeNoto', true)
                    allocRecognition = ...
                        engineModel(allocC).noto;
                end

                allocWearFactor = 1;

                allocContinuityValue = pb_get( ...
                    engineContinuity, ...
                    engineIds{allocC}, ...
                    0);

                if pb_get(opt, 'homeUsure', false) ...
                        && engineKappa ~= 0 ...
                        && allocContinuityValue ~= 0

                    allocWearFamilies = pb_cells( ...
                        pb_get(opt, 'usureFam', {}));

                    allocWearApplies = ...
                        ~isfield(opt, 'usureFam') ...
                        || any(strcmp( ...
                        allocWearFamilies, ...
                        allocHomeFamily));

                    if allocWearApplies
                        allocWearFactor = ...
                            1 ...
                            - engineKappa ...
                            * allocContinuityValue;
                    end

                end

                allocOwnWeight = ...
                    engineProbabilities( ...
                    allocC, ...
                    allocCategoryIndex) ...
                    ^ allocPowerHome ...
                    * ( ...
                    1 ...
                    + (allocHomeGain - 1) ...
                    * allocRecognition ...
                    * allocWearFactor ...
                );

                if allocHomeShare ~= 1
                    allocOwnWeight = ...
                        allocOwnWeight * allocHomeShare;
                end

                if allocHomeShare < 1
                    allocOwnWeight = ...
                        allocOwnWeight ...
                        + (1 - allocHomeShare) ...
                        * allocOtherWeight;
                end

                allocWeights(allocC) = ...
                    allocOwnWeight * allocMultiplier;

            else
                allocWeights(allocC) = ...
                    allocOtherWeight * allocMultiplier;
            end

        end

        % Force de chaque groupe : maximum de ses candidats

        allocUniqueKeys = {};
        allocMembers = {};
        allocMaxima = [];

        for allocC = 1:engineCandidateCount
            allocGroupIndex = find( ...
                strcmp( ...
                allocUniqueKeys, ...
                allocGroupKeys{allocC}), ...
                1);

            if isempty(allocGroupIndex)
                allocUniqueKeys{end + 1} = ...
                    allocGroupKeys{allocC};

                allocMembers{end + 1} = allocC;

                allocMaxima(end + 1) = max( ...
                    0, ...
                    allocWeights(allocC));

            else
                allocMembers{allocGroupIndex}(end + 1) = ...
                    allocC;

                allocMaxima(allocGroupIndex) = max( ...
                    allocMaxima(allocGroupIndex), ...
                    allocWeights(allocC));
            end

        end

        % Part dirigée vers l'abstention

        allocAbstentionWeight = ...
            engineProbabilities( ...
            end, ...
            allocCategoryIndex) ...
            ^ allocBeta ...
            * allocAbsorption;

        allocDenominator = ...
            sum(allocMaxima) + allocAbstentionWeight;

        if allocDenominator <= 0
            allocAbstention = allocMass;
            return
        end

        % Distribution entre groupes, puis dans chaque groupe

        for allocK = 1:numel(allocUniqueKeys)
            allocSelected = allocMembers{allocK};

            allocGroupWeight = sum( ...
                allocWeights(allocSelected));

            if allocGroupWeight > 0
                allocGroupMass = ...
                    allocMass ...
                    * allocMaxima(allocK) ...
                    / allocDenominator;

                engineVotes( ...
                    allocSelected, ...
                    allocCategoryIndex) = ...
                    engineVotes( ...
                    allocSelected, ...
                    allocCategoryIndex) ...
                    + allocGroupMass ...
                    * allocWeights(allocSelected)' ...
                    / allocGroupWeight;
            end

        end

        allocAbstention = ...
            allocMass ...
            * allocAbstentionWeight ...
            / allocDenominator;
    end

    function freeAbstention = allocateFree( ...
            freeCategoryIndex, ...
            freeMass, ...
            freeZoneId, ...
            freeAbsorption)

        if freeMass == 0
            freeAbstention = 0;
            return
        end

        freeZoneData = getZone(freeZoneId);

        freeSigma = pb_get( ...
            opt, ...
            'freeSigma', ...
            0.25);

        freeWeights = zeros( ...
            engineCandidateCount, ...
            1);

        freeForceConfig = pb_get( ...
            opt, ...
            'force', ...
            struct());

        for freeC = 1:engineCandidateCount
            freePosition = pb_get( ...
                engineModel(freeC), ...
                'pos', ...
                pb_get( ...
                engineModel(freeC), ...
                'by_hist', ...
                freeZoneData.mu));

            freeDistanceSquared = sum( ...
                (freePosition(:) - freeZoneData.mu(:)) .^ 2);

            freeWeights(freeC) = ...
                engineProbabilities( ...
                freeC, ...
                freeCategoryIndex) ...
                ^ engineBeta ...
                * exp( ...
                -freeDistanceSquared ...
                / (2 * freeSigma ^ 2)) ...
                * pb_get( ...
                freeForceConfig, ...
                engineIds{freeC}, ...
                1);
        end

        freeAbstentionWeight = ...
            engineProbabilities( ...
            end, ...
            freeCategoryIndex) ...
            ^ engineBeta ...
            * freeAbsorption;

        freeDenominator = ...
            sum(freeWeights) + freeAbstentionWeight;

        if freeDenominator <= 0
            freeAbstention = freeMass;
            return
        end

        engineVotes(:, freeCategoryIndex) = ...
            engineVotes(:, freeCategoryIndex) ...
            + freeMass * freeWeights / freeDenominator;

        freeAbstention = ...
            freeMass ...
            * freeAbstentionWeight ...
            / freeDenominator;
    end

