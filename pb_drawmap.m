function pb_drawmap(ax, D, result, showPCS)
%PB_DRAWMAP Carte sociale des candidats, inactifs inclus.
%
% Les positions sont calculées dans pb_engine.
% Cette fonction affiche :
%   - les bulles des candidats ;
%   - le barycentre général ;
%   - éventuellement les repères des catégories sociales.
%
% La surface des bulles est proportionnelle au score simulé.

    if nargin < 4
        showPCS = false;
    end

    cla(ax);
    hold(ax, 'on');

    mapBackground = [0.95, 0.95, 0.92];

    set( ...
        ax, ...
        'Color', ...
        mapBackground);

    %% Résultats à afficher

    mapCoordinates = result.coordinates;
    mapBarycentre = result.barycentre;

    mapValidCandidates = all( ...
        isfinite(mapCoordinates), ...
        2);

    mapVisiblePoints = ...
        mapCoordinates(mapValidCandidates, :);

    %% Positions des catégories sociales

    mapCategoryCount = numel(D.core.pcs);

    mapCategoryPositions = zeros( ...
        mapCategoryCount, ...
        2);

    mapCategoryIds = cell( ...
        1, ...
        mapCategoryCount);

    for mapCategoryIndex = 1:mapCategoryCount
        mapCategoryId = ...
            D.core.pcs(mapCategoryIndex).id;

        mapCategoryIds{mapCategoryIndex} = ...
            mapCategoryId;

        if strcmp(mapCategoryId, 'inact')

            mapCategoryPoint = [ ...
                -2.5687835393427796, ...
                -3.3472027936890765];

        elseif isfield( ...
                D.history.POSTES, ...
                mapCategoryId)

            mapCategoryPoint = ...
                D.history.POSTES.(mapCategoryId);

        else
            error( ...
                'Pollbuster:MissingSocialPosition', ...
                'Coordonnees sociales absentes pour "%s".', ...
                mapCategoryId);
        end

        mapCategoryPositions(mapCategoryIndex, :) = ...
            mapCategoryPoint(:)';
    end

    if showPCS
        mapVisiblePoints = [ ...
            mapVisiblePoints; ...
            mapCategoryPositions];
    end

    %% Limites de la carte

    if isempty(mapVisiblePoints)
        mapVisiblePoints = [ ...
            -1, -1; ...
             1,  1];
    end

    if all(isfinite(mapBarycentre))
        mapVisiblePoints = [ ...
            mapVisiblePoints; ...
            mapBarycentre];
    end

    mapLower = min( ...
        mapVisiblePoints, ...
        [], ...
        1);

    mapUpper = max( ...
        mapVisiblePoints, ...
        [], ...
        1);

    mapSpan = max( ...
        mapUpper - mapLower, ...
        [2, 2]);

    mapLower = ...
        mapLower - 0.20 * mapSpan;

    mapUpper = ...
        mapUpper + 0.25 * mapSpan;

    %% Fond pointillé

    [mapGridX, mapGridY] = meshgrid( ...
        linspace(mapLower(1), mapUpper(1), 40), ...
        linspace(mapLower(2), mapUpper(2), 24));

    plot( ...
        ax, ...
        mapGridX(:), ...
        mapGridY(:), ...
        '.', ...
        'Color', [0.77, 0.79, 0.74], ...
        'MarkerSize', 3);

    %% Axes passant par le barycentre

    if all(isfinite(mapBarycentre))
        plot( ...
            ax, ...
            [mapLower(1), mapUpper(1)], ...
            [mapBarycentre(2), mapBarycentre(2)], ...
            '-', ...
            'Color', [0.53, 0.56, 0.50]);

        plot( ...
            ax, ...
            [mapBarycentre(1), mapBarycentre(1)], ...
            [mapLower(2), mapUpper(2)], ...
            '-', ...
            'Color', [0.53, 0.56, 0.50]);
    end

    %% Repères des catégories sociales

    if showPCS
        plot( ...
            ax, ...
            mapCategoryPositions(:, 1), ...
            mapCategoryPositions(:, 2), ...
            'x', ...
            'Color', [0.40, 0.43, 0.39], ...
            'MarkerSize', 8, ...
            'LineWidth', 1);

        for mapCategoryIndex = 1:mapCategoryCount
            text( ...
                ax, ...
                mapCategoryPositions(mapCategoryIndex, 1), ...
                mapCategoryPositions(mapCategoryIndex, 2), ...
                [' ', mapCategoryIds{mapCategoryIndex}], ...
                'Color', [0.38, 0.40, 0.36], ...
                'FontSize', 9, ...
                'Interpreter', 'none');
        end
    end

    %% Bulles et étiquettes des candidats

    [~, mapCandidateOrder] = sort( ...
        result.pct, ...
        'descend');

    mapLabelOffsetX = ...
        0.02 * (mapUpper(1) - mapLower(1));

    mapLabelOffsetY = ...
        0.035 * (mapUpper(2) - mapLower(2));

    mapOccupiedLabels = zeros(0, 2);

    for mapOrderIndex = 1:numel(mapCandidateOrder)
        mapCandidateIndex = ...
            mapCandidateOrder(mapOrderIndex);

        if ~mapValidCandidates(mapCandidateIndex)
            continue
        end

        mapCandidate = ...
            result.candidates{mapCandidateIndex};

        mapHexColor = ...
            D.colors.(mapCandidate.zone);

        mapRGBColor = sscanf( ...
            mapHexColor(2:end), ...
            '%2x%2x%2x', ...
            [1, 3]) / 255;

        mapBubbleArea = max( ...
            1, ...
            55 * result.pct(mapCandidateIndex));

        scatter( ...
            ax, ...
            mapCoordinates(mapCandidateIndex, 1), ...
            mapCoordinates(mapCandidateIndex, 2), ...
            mapBubbleArea, ...
            mapRGBColor, ...
            'filled', ...
            'MarkerEdgeColor', 'white', ...
            'LineWidth', 1);

        mapLabelX = ...
            mapCoordinates(mapCandidateIndex, 1) ...
            + mapLabelOffsetX;

        mapLabelY = ...
            mapCoordinates(mapCandidateIndex, 2) ...
            + mapLabelOffsetY;

        % Décalage simple des étiquettes trop proches.

        while ~isempty(mapOccupiedLabels)

            mapCollision = any( ...
                abs(mapOccupiedLabels(:, 1) - mapLabelX) ...
                    < 0.20 * (mapUpper(1) - mapLower(1)) ...
                & ...
                abs(mapOccupiedLabels(:, 2) - mapLabelY) ...
                    < 1.4 * mapLabelOffsetY);

            if ~mapCollision
                break
            end

            mapLabelY = ...
                mapLabelY + 1.6 * mapLabelOffsetY;
        end

        mapOccupiedLabels(end + 1, :) = [ ...
            mapLabelX, ...
            mapLabelY];

        plot( ...
            ax, ...
            [ ...
                mapCoordinates(mapCandidateIndex, 1), ...
                mapLabelX ...
            ], ...
            [ ...
                mapCoordinates(mapCandidateIndex, 2), ...
                mapLabelY ...
            ], ...
            '-', ...
            'Color', [0.60, 0.62, 0.57], ...
            'LineWidth', 0.5);

        mapCandidateName = pb_get( ...
            D.names, ...
            result.ids{mapCandidateIndex}, ...
            result.ids{mapCandidateIndex});

        text( ...
            ax, ...
            mapLabelX, ...
            mapLabelY, ...
            sprintf( ...
                '%s %.2f %%', ...
                mapCandidateName, ...
                result.pct(mapCandidateIndex)), ...
            'FontSize', 10, ...
            'Interpreter', 'none', ...
            'Color', [0.15, 0.16, 0.14]);
    end

    %% Noms des axes

    if all(isfinite(mapBarycentre))
        text( ...
            ax, ...
            mapLower(1), ...
            mapBarycentre(2), ...
            'travail', ...
            'VerticalAlignment', 'bottom');

        text( ...
            ax, ...
            mapUpper(1), ...
            mapBarycentre(2), ...
            'capital', ...
            'HorizontalAlignment', 'right', ...
            'VerticalAlignment', 'bottom');

        text( ...
            ax, ...
            mapBarycentre(1), ...
            mapUpper(2), ...
            ' direction', ...
            'VerticalAlignment', 'top');

        text( ...
            ax, ...
            mapBarycentre(1), ...
            mapLower(2), ...
            ' subordination', ...
            'VerticalAlignment', 'bottom');
    end

    %% Présentation finale

    xlim( ...
        ax, ...
        [mapLower(1), mapUpper(1)]);

    ylim( ...
        ax, ...
        [mapLower(2), mapUpper(2)]);

    set( ...
        ax, ...
        'XTick', [], ...
        'YTick', [], ...
        'Box', 'off');

    title( ...
        ax, ...
        sprintf( ...
            'Simulation V18 | %.2f M de suffrages exprimes', ...
            result.E / 1e6));

    xlabel( ...
        ax, ...
        'Surface proportionnelle au score ; carte avec inactifs');

    hold(ax, 'off');

end